"""packages/lifecycle/render.py — render lifecycles as a readable map.

The generated document is the UX/AX surface of this layer: a person can read
one page instead of forty modules, and an agent can be handed ``--json`` or the
Markdown straight from the CLI.  Rendering is deterministic so the generated
file can be compared byte-for-byte in CI; see ``scripts/lifecycles.py check``.
"""
from __future__ import annotations

import re
from typing import Any, Iterable, Sequence

from packages.lifecycle.machine import StateMachine

_SAFE_ID = re.compile(r"[^A-Za-z0-9_]")


def _state_id(state: str) -> str:
    return "s_" + _SAFE_ID.sub("_", state)


def mermaid(machine: StateMachine) -> str:
    """A Mermaid ``stateDiagram-v2`` block for ``machine``."""
    lines = ["```mermaid", "stateDiagram-v2"]
    for state in sorted(machine.states):
        label = f"{state} (resting)" if state in machine.terminal else state
        lines.append(f'    state "{label}" as {_state_id(state)}')
    lines.append(f"    [*] --> {_state_id(machine.initial)}")
    for source in sorted(machine.states):
        for target in sorted(machine.transitions[source]):
            lines.append(f"    {_state_id(source)} --> {_state_id(target)}")
    for state in sorted(machine.terminal):
        if not machine.transitions[state]:
            lines.append(f"    {_state_id(state)} --> [*]")
    lines.append("```")
    return "\n".join(lines)


def transition_table(machine: StateMachine) -> str:
    """A compact table of every declared move, one row per source state."""
    rows = ["| From | To |", "|------|----|"]
    for source in sorted(machine.states):
        targets = ", ".join(sorted(machine.transitions[source])) or "— (resting)"
        rows.append(f"| `{source}` | {targets} |")
    return "\n".join(rows)


def render_markdown(
    machines: Sequence[StateMachine], findings: Iterable[Any] = ()
) -> str:
    """The full generated document for ``machines`` and ``findings``."""
    lines = [
        "# Lifecycles",
        "",
        "> Generated by `python scripts/lifecycles.py docs --write`. Do not edit by",
        "> hand: `python scripts/lifecycles.py check` fails when this file is stale.",
        "",
        "Every status field this app owns, the states it can hold, and the moves it",
        f"declares. {len(machines)} lifecycles are registered.",
        "",
        "Read one without opening the source:",
        "",
        "```bash",
        "python scripts/lifecycles.py list                 # one line per lifecycle",
        "python scripts/lifecycles.py show task            # states + legal moves",
        "python scripts/lifecycles.py show task --json     # for a tool or an agent",
        "python scripts/lifecycles.py mermaid task         # diagram only",
        "```",
        "",
        "## Map",
        "",
        "| Lifecycle | Initial | Resting | States | Declared in |",
        "|-----------|---------|---------|--------|-------------|",
    ]
    for machine in machines:
        resting = ", ".join(f"`{s}`" for s in sorted(machine.terminal)) or "—"
        lines.append(
            f"| [`{machine.name}`](#{machine.name}) "
            f"| `{machine.initial}` | {resting} | {len(machine.states)} "
            f"| `{machine.owner}` |"
        )
    lines.append("")

    for machine in machines:
        lines += [
            f"## {machine.name}",
            "",
            machine.description,
            "",
            f"- **Owner:** `{machine.owner}`",
            *(
                [f"- **Status type:** `{machine.status_type}`"]
                if machine.status_type
                else []
            ),
            f"- **Initial:** `{machine.initial}`",
            "- **Resting:** "
            + (", ".join(f"`{s}`" for s in sorted(machine.terminal)) or "none"),
        ]
        if machine.notes:
            lines += ["- **Notes:**", *(f"  - {note}" for note in machine.notes)]
        unreachable = machine.unreachable()
        if unreachable:
            lines.append(
                "- **No incoming edge from the initial state:** "
                + ", ".join(f"`{s}`" for s in unreachable)
                + " (written by a dedicated path or legacy data)"
            )
        lines += ["", mermaid(machine), "", transition_table(machine), ""]

    findings = list(findings)
    if findings:
        lines += ["## Findings", ""]
        for index, finding in enumerate(findings, start=1):
            machines_involved = ", ".join(f"`{m}`" for m in finding.machines)
            lines += [
                f"### {index}. {finding.title}",
                "",
                finding.detail,
                "",
                f"Lifecycles: {machines_involved}",
                "",
            ]
    return "\n".join(lines).rstrip() + "\n"
